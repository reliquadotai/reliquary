"""Replayed episodes for the async reference miner (validator side: ``validator/rl_suite_episodes``).

A lease of a replayed env (a deterministic tool world, registry ``interaction_mode="episode"``: EnvScaler) is
played here, in this process: the world is the env's pinned package, run by the RL ``EpisodeRunner`` that the
validator's replay runs too, every model turn generated by the forced episode engine (``corpus_generate_server.
GenerateEngine``, the signed episodes' engine) on a session bound to the lease's draw (``LeaseDrawBinding``: the
draw is keyed per model-token position across turns). No sandbox, no transcript: the validator recomputes every
observation.

An episode ends as the replay will read it: the world ended it (``agent_completed``), the turn limit
(``max_turns``), or the next turn has no room under the episode's token budget (``context_length``: a cut,
scored 0). Its completion is everything after the prompt up to the end of its last model turn. Submission is
mandatory and an episode cannot be withheld: when one of the lease's episodes cannot be kept (the engine failed, a
check the validator runs refuses it) the whole lease fails (``EpisodeLeaseFailed``), as for a signed episode.
"""
from __future__ import annotations

import asyncio
import concurrent.futures
import logging
import os
import secrets
from collections.abc import Callable, Sequence
from typing import Any

logger = logging.getLogger(__name__)

EPISODE_THREADS = int(os.environ.get("RELIQUARY_RL_SUITE_EPISODE_THREADS", "512"))


class _NoRoom(Exception):
    """The next turn has no room under the episode's token budget."""


class _LeasePolicy:
    """One episode's turns, each generated by the engine on the event loop while the runner waits in its worker
    thread; the spans and the context are recorded here (a cut episode never returns a trace)."""

    def __init__(self, *, engine, session_id: str, loop: asyncio.AbstractEventLoop, decode: Callable,
                 max_total_tokens: int) -> None:
        self._engine, self._session, self._loop, self._decode = engine, session_id, loop, decode
        self._max_total = int(max_total_tokens)
        self.spans: list[tuple[int, int]] = []
        self.context: list[int] = []

    def generate(self, *, tokens: tuple[int, ...], **_: object):
        from reliquary.environment.agentic.types import GeneratedAction

        self.context = [int(t) for t in tokens]
        if self._max_total - len(tokens) < 1:
            raise _NoRoom()
        answer = asyncio.run_coroutine_threadsafe(
            self._engine.generate(self._session, list(tokens), None), self._loop).result()
        ids = [int(t) for t in answer["choices"][0]["token_ids"]]
        self.spans.append((len(tokens), len(tokens) + len(ids)))
        self.context = [*self.context, *ids]
        return GeneratedAction(text=self._decode(ids), tokens=tuple(ids))


class SuiteLeasePlayer:
    """The lease episodes of one replayed env: ``policy`` (``rl_suite_episodes.SuiteLeasePolicy``),
    ``environment`` (the env, built once), ``codec`` (the checkpoint tokenizer's ``TokenizerCodec``, as the
    validator's replay workers code), ``engine`` (the forced generate engine host) and ``draws`` (its
    ``ForcedDraws``)."""

    def __init__(self, *, policy, environment, codec, engine, draws, rollouts: int = 16,
                 threads: int = EPISODE_THREADS) -> None:
        from reliquary.environment.agentic.renderers import renderer_for

        self.policy, self.environment, self.codec = policy, environment, codec
        self._engine, self._draws, self.rollouts = engine, draws, int(rollouts)
        self.renderer = renderer_for(policy.renderer_id, codec.encode)
        # An episode holds a thread from its first turn to its last (the runner waits on each turn): the loop's
        # default executor (min(32, cpus + 4) threads) would cap the episodes in flight below the engine's
        # sequences and queue every other to_thread call of the miner behind them.
        self._threads = concurrent.futures.ThreadPoolExecutor(max_workers=max(1, int(threads)),
                                                              thread_name_prefix="rl-suite-episode")

    def prompt_ids(self, prompt_idx: int) -> list[int]:
        return [int(t) for t in self.renderer.encode_initial(self.environment.get_task(int(prompt_idx)))]

    def _run(self, task, seed: int, policy: _LeasePolicy):
        from reliquary.environment.agentic.runner import EpisodeRunner

        # No max_episode_tokens: the runner would count the final suffix and the observation after the last turn,
        # which the completion never holds. The engine caps each turn at what is left of the budget, and a turn
        # with no room left ends the episode (``_NoRoom``).
        return EpisodeRunner(renderer=self.renderer, max_turns=self.policy.max_turns,
                             max_observation_bytes=self.policy.max_observation_bytes,
                             ).run(self.environment, task, seed=seed, policy=policy)

    async def play_one(self, lease, index: int, prompt: Sequence[int]):
        """One rollout: ``(tokens, spans, stop)`` (completion-relative), or raises."""
        from reliquary.corpus.suite_episode import replay_stop
        from reliquary.miner.forced_draw import LeaseDrawBinding
        from reliquary.validator.rl_suite_episodes import CONTEXT_LENGTH, lease_episode_seed

        session_id = f"rl-suite-{secrets.token_hex(12)}"
        self._draws.bind(session_id, LeaseDrawBinding(lease.nonce, int(lease.prompt_idx), int(lease.checkpoint),
                                                      int(index)))
        policy = _LeasePolicy(engine=self._engine, session_id=session_id, loop=asyncio.get_running_loop(),
                              decode=self.codec.decode, max_total_tokens=self.policy.max_episode_tokens)
        try:
            task = self.environment.get_task(int(lease.prompt_idx))
            try:
                trace = await asyncio.get_running_loop().run_in_executor(
                    self._threads, self._run, task, lease_episode_seed(lease), policy)
            except _NoRoom:
                trace = None
        finally:
            self._draws.drop(session_id)
            take = getattr(self._engine, "take_session", None)
            if take is not None:
                try:
                    take(session_id)               # the turn log is not needed: the validator replays
                except Exception:
                    logger.debug("taking generate session %s failed", session_id, exc_info=True)
        if trace is None:
            spans, context, stop = list(policy.spans), policy.context, CONTEXT_LENGTH
        else:
            spans, context, stop = [tuple(s) for s in trace.assistant_spans], list(trace.tokens), replay_stop(trace)
        if not spans:
            raise RuntimeError("no model turn")
        offset, end = len(prompt), int(spans[-1][1])
        if [int(t) for t in context[:offset]] != list(prompt):
            raise RuntimeError("the episode's prompt is not the task's")
        return (tuple(int(t) for t in context[offset:end]),
                tuple((int(s) - offset, int(e) - offset) for s, e in spans), str(stop))

    async def play(self, lease) -> list[Any]:
        """The lease's ``rollouts`` episodes (``rl_async.EpisodeRollout`` with an empty transcript), played side by
        side; ``EpisodeLeaseFailed`` when one cannot be kept."""
        from reliquary.miner.rl_async import EpisodeRollout
        from reliquary.miner.rl_async_episodes import EpisodeLeaseFailed
        from reliquary.validator.rl_suite_episodes import turn_refusal

        label = f"lease {lease.lease_id[:12]}"
        prompt = self.prompt_ids(lease.prompt_idx)
        outcomes = await asyncio.gather(*(self.play_one(lease, i, prompt) for i in range(self.rollouts)),
                                        return_exceptions=True)
        kept = []
        for index, outcome in enumerate(outcomes):
            if isinstance(outcome, BaseException):
                why = f"rollout {index}: {type(outcome).__name__}: {outcome}"
                logger.warning("%s cannot be submitted: %s", label, why)
                raise EpisodeLeaseFailed(why)
            tokens, spans, stop = outcome
            refusal = turn_refusal(self.policy, prompt_len=len(prompt), tokens=list(tokens), spans=spans,
                                   encode=self.codec.encode, decode=self.codec.decode)
            if refusal is not None:
                why = f"rollout {index}: {refusal[0]} {refusal[1]}"
                logger.warning("%s cannot be submitted: %s", label, why)
                raise EpisodeLeaseFailed(why)
            kept.append(EpisodeRollout(tokens, spans, stop, {}))
        return kept


def build_suite_players(names: Sequence[str], *, engine, draws, tokenizer, profile=None,
                        environments=None, rollouts: int = 16) -> dict[str, SuiteLeasePlayer]:
    """The players of the miner's replayed envs on one engine. Blocking: each env is built."""
    from reliquary.corpus.suite_episode import TokenizerCodec
    from reliquary.environment import load_episode_environment
    from reliquary.validator.rl_suite_episodes import suite_lease_policy

    codec = TokenizerCodec(tokenizer)
    out = {}
    for name in names:
        environment = (environments or {}).get(name) or load_episode_environment(name)
        policy = suite_lease_policy(name, profile=profile, environment=environment)
        out[name] = SuiteLeasePlayer(policy=policy, environment=environment, codec=codec, engine=engine,
                                     draws=draws, rollouts=rollouts)
    return out


__all__ = ["SuiteLeasePlayer", "build_suite_players"]
